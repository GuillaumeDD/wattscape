/**
 * Bakes each region's typical range of consumption (B-014) into
 * `src/map/consumption.ts`: the 5th and 95th percentiles of `consommation` over
 * twelve months of RTE's consolidated and definitive regional éCO2mix (DS-12), which
 * light the towns at night (ARCHITECTURE § Data-to-scene mapping). Run by hand,
 * never in CI, then commit the file:
 *
 *   node --experimental-strip-types tools/bake-consumption.ts
 *
 * One request: ODRÉ computes the percentiles per region (ODSQL `percentile`).
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { REGION_CODES } from "../src/data/eco2mix.ts";

const OUT = "src/map/consumption.ts";
export const CONSUMPTION_DATASET = "eco2mix-regional-cons-def";
/** Twelve whole months, the last the dataset holds (it ends on 31 August 2026). */
const FROM = "2025-09-01";
const TO = "2026-09-01";

const url = `https://odre.opendatasoft.com/api/explore/v2.1/catalog/datasets/${CONSUMPTION_DATASET}/records?${new URLSearchParams(
  {
    select:
      "code_insee_region, percentile(consommation, 5) as p5, percentile(consommation, 95) as p95, min(consommation) as low, max(consommation) as high, count(*) as n",
    where: `consommation is not null and date_heure >= date'${FROM}' and date_heure < date'${TO}'`,
    group_by: "code_insee_region",
    limit: "20",
  },
).toString()}`;

async function get(): Promise<unknown> {
  for (let attempt = 1; ; attempt++) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`HTTP ${String(response.status)} for ${url}`);
      return await response.json();
    } catch (error) {
      // ODRÉ sometimes resets the connection: retry with growing pauses.
      if (attempt === 8) throw error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 2000));
    }
  }
}

interface Row {
  readonly code_insee_region: string;
  readonly p5: number;
  readonly p95: number;
  readonly low: number;
  readonly high: number;
  readonly n: number;
}
const answer = (await get()) as { results?: Row[] };
const rows = answer.results ?? [];
const byRegion = new Map(rows.map((r) => [r.code_insee_region, r]));
const lines: string[] = [];
for (const region of REGION_CODES) {
  const r = byRegion.get(region);
  // Twelve months of half-hours: about 17 500 steps; fewer means a hole in the data.
  if (r === undefined || !(r.n > 17_000) || !(r.p5 > 0) || !(r.p95 > r.p5))
    throw new Error(`region ${region}: unexpected answer ${JSON.stringify(r)}`);
  lines.push(
    `  "${region}": { p5: ${String(Math.round(r.p5))}, p95: ${String(Math.round(r.p95))} },`,
  );
  console.log(
    `${region}: p5 ${r.p5.toFixed(0)}, p95 ${r.p95.toFixed(0)} MW (min ${r.low.toFixed(0)}, max ${r.high.toFixed(0)}, ${String(r.n)} steps)`,
  );
}

const BAKED_ON = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `/**
 * Each region's typical range of consumption (B-014), which lights the towns at
 * night. GENERATED by tools/bake-consumption.ts on ${BAKED_ON}: do not edit, re-bake.
 *
 * The 5th and 95th percentiles of \`consommation\` (MW) from ${FROM} to ${TO} (excluded):
 * RTE « Données éCO2mix régionales consolidées et définitives », via ODRÉ (DS-12),
 * Licence Ouverte 2.0.
 */
import { type RegionCode } from "../data/eco2mix.ts";

/** Day of the bake, and the twelve months it reads. */
export const CONSUMPTION_BAKED_ON = "${BAKED_ON}";
export const CONSUMPTION_PERIOD = { from: "${FROM}", to: "${TO}" } as const;

/** Each region's consumption, MW: low (5th percentile) and high (95th) over the year. */
export const CONSUMPTION_RANGES: Readonly<
  Record<RegionCode, { readonly p5: number; readonly p95: number }>
> = {
${lines.join("\n")}
};
`,
);
// The committed file follows the repository's formatting.
execFileSync("npx", ["prettier", "--write", OUT], { stdio: "inherit" });
